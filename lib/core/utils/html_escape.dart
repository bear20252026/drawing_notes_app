// 此前 HTML 导出与 SVG 导出各持一份相同的实体替换链。收敛为唯一实现。
// 转义集与原实现一致：& < > "（单引号不在集内——双引号属性场景安全）。
// 顺序敏感：必须先替换 &，否则会把后续实体里的 & 二次转义。

/// 转义 HTML/XML 特殊字符（防注入/破版）。
String escapeHtml(String raw) => raw
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;');
