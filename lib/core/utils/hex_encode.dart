// ============================================================================
// hex_encode.dart —— 字节 → 小写十六进制（去重收敛 2026-09-07）
// ============================================================================
//
// 此前同一拼接 `.map((b) => b.toRadixString(16).padLeft(2, '0')).join()`
// 散落在安全/存储层多处（盐编码、随机 tmp 后缀、HMAC 签名等）。收敛为
// 唯一实现，语义固定：每字节两位、小写、无分隔符。
//
// 注意与「颜色 hex」区分：颜色是单个 int 的 #RRGGBB 大写/六位格式，
// 不是字节序列，不在收敛范围。

/// 字节序列 → 小写十六进制字符串（每字节两位补零，无分隔符）。
String hexEncode(List<int> bytes) =>
    bytes.map((b) => b.toRadixString(16).padLeft(2, '0')).join();
